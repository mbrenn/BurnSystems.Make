using System.Text;

namespace BurnSystems.Make.BuildAgent;

/// <summary>
/// Some helper for files
/// </summary>
public static class FileHelper
{
    /// <summary>
    /// Merges two files into a resulting file
    /// </summary>
    /// <param name="options">Options of the merging</param>
    /// <returns>true, if the target file has actually been written. false, if the merge has been
    /// skipped because the target file is not outdated</returns>
    public static bool MergeFiles(FileMergeOptions options)
    {
        ArgumentNullException.ThrowIfNull(options);

        if (!File.Exists(options.FirstFile))
        {
            throw new FileNotFoundException("The first file to be merged was not found", options.FirstFile);
        }

        if (!File.Exists(options.SecondFile))
        {
            throw new FileNotFoundException("The second file to be merged was not found", options.SecondFile);
        }

        if (IsSamePath(options.TargetFile, options.FirstFile)
            || IsSamePath(options.TargetFile, options.SecondFile))
        {
            throw new InvalidOperationException(
                $"The target file '{options.TargetFile}' must not be one of the source files");
        }

        if (options.OnlyIfModified && !IsTargetOutdated(options))
        {
            return false;
        }

        var targetDirectory = Path.GetDirectoryName(Path.GetFullPath(options.TargetFile));
        if (!string.IsNullOrEmpty(targetDirectory))
        {
            Directory.CreateDirectory(targetDirectory);
        }

        using var target = new FileStream(options.TargetFile, FileMode.Create, FileAccess.Write);

        if (!string.IsNullOrEmpty(options.PrefixTextTarget))
        {
            target.Write(Encoding.UTF8.GetBytes(options.PrefixTextTarget));
        }

        AppendTo(target, options.FirstFile);
        AppendTo(target, options.SecondFile);

        return true;
    }

    /// <summary>
    /// Checks whether the target file needs to be recreated because it does not exist yet
    /// or because at least one of the source files is newer than the target file
    /// </summary>
    /// <param name="options">Options of the merging</param>
    /// <returns>true, if the target file shall be recreated</returns>
    private static bool IsTargetOutdated(FileMergeOptions options)
    {
        if (!File.Exists(options.TargetFile))
        {
            return true;
        }

        var targetTime = File.GetLastWriteTimeUtc(options.TargetFile);
        return File.GetLastWriteTimeUtc(options.FirstFile) > targetTime
               || File.GetLastWriteTimeUtc(options.SecondFile) > targetTime;
    }

    /// <summary>
    /// Appends the complete content of the given file to the stream
    /// </summary>
    /// <param name="target">Stream to which the content is written</param>
    /// <param name="path">Path of the file being appended</param>
    private static void AppendTo(Stream target, string path)
    {
        using var source = new FileStream(path, FileMode.Open, FileAccess.Read);
        source.CopyTo(target);
    }

    /// <summary>
    /// Checks whether the two given paths point to the same file
    /// </summary>
    /// <param name="first">First path to be compared</param>
    /// <param name="second">Second path to be compared</param>
    /// <returns>true, if both paths are equal</returns>
    private static bool IsSamePath(string first, string second)
    {
        var comparison = EnvironmentHelper.IsWindows()
            ? StringComparison.OrdinalIgnoreCase
            : StringComparison.Ordinal;

        return string.Equals(Path.GetFullPath(first), Path.GetFullPath(second), comparison);
    }
}

/// <summary>
/// Defines the options of how to merge two file
/// </summary>
public class FileMergeOptions
{
    /// <summary>
    /// Stores the path to the first file being used to merge the file
    /// </summary>
    public required string FirstFile { get; set; }
    
    /// <summary>
    /// Stores the path to the second file being used to merge the file
    /// </summary>
    public required string SecondFile { get; set; }
    
    /// <summary>
    /// Stores the path of the file in which the data shall be merged
    /// </summary>
    public required string TargetFile { get; set; }

    /// <summary>
    /// Defines the text that is used for prefixing the target
    /// </summary>
    public string PrefixTextTarget { get; set; } = "// This file is autogenerated\r\n";

    /// <summary>
    /// Flags indicating whether the merge shall only be performed in case the target file is older
    /// compared to one of the other files
    /// </summary>
    public bool OnlyIfModified { get; set; } = true;
}